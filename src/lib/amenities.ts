import amenityData from "@/data/suburb_amenities.json";

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface AmenityItem {
  name: string;
  distance_km: number;
  lat: number;
  lng: number;
}

export interface SuburbAmenities {
  hospitals: AmenityItem[];
  schools: AmenityItem[];
  universities: AmenityItem[];
  fire_stations: AmenityItem[];
  police: AmenityItem[];
  childcare: AmenityItem[];
}

export interface AmenitySummary {
  hospital_count: number;
  school_count: number;
  university_count: number;
  fire_station_count: number;
  police_count: number;
  childcare_count: number;
}

// ---------------------------------------------------------------------------
// Data access
//
// suburb_amenities.json is generated by scripts/build-amenities.mjs: per
// postcode, the nearest 15 named items per category within 5 km of the
// postcode centroid. Counts are therefore capped at 15.
// ---------------------------------------------------------------------------

const data = amenityData as Record<string, SuburbAmenities>;

/**
 * Whether the amenity dataset has an entry for this postcode. A postcode
 * without an entry has NO DATA, which is different from having no amenities:
 * callers must not score or filter it as if it had none.
 */
export function hasAmenityData(postcode: string): boolean {
  return Object.hasOwn(data, postcode);
}

/** Full amenity lists for a postcode, or null when there is no data for it. */
export function getAmenities(postcode: string): SuburbAmenities | null {
  return hasAmenityData(postcode) ? data[postcode] : null;
}

/** Counts per category for a postcode, or null when there is no data for it. */
export function getAmenitySummary(postcode: string): AmenitySummary | null {
  const a = getAmenities(postcode);
  if (!a) return null;
  return {
    hospital_count: a.hospitals.length,
    school_count: a.schools.length,
    university_count: a.universities.length,
    fire_station_count: a.fire_stations.length,
    police_count: a.police.length,
    childcare_count: a.childcare.length,
  };
}

/**
 * Calculate an amenity score (0–100) for a postcode, or null when there is
 * no data for it.
 *
 * Scoring:
 * - Hospital within 2 km:      +25
 * - 3+ schools within 5 km:    +25
 * - University within 5 km:    +15
 * - Fire station within 5 km:  +10
 * - Police within 5 km:        +10
 * - Childcare within 3 km:     +15
 */
export function getAmenityScore(postcode: string): number | null {
  const a = getAmenities(postcode);
  if (!a) return null;
  let score = 0;

  if (a.hospitals.some((h) => h.distance_km <= 2)) score += 25;
  if (a.schools.filter((s) => s.distance_km <= 5).length >= 3) score += 25;
  if (a.universities.some((u) => u.distance_km <= 5)) score += 15;
  if (a.fire_stations.some((f) => f.distance_km <= 5)) score += 10;
  if (a.police.some((p) => p.distance_km <= 5)) score += 10;
  if (a.childcare.some((c) => c.distance_km <= 3)) score += 15;

  return score;
}
